"""7. Анализ пяти чисел"""

numbers = []

for i in range(5):
    number = float(input(f"Введите число {i + 1}: "))
    numbers.append(number)

all_unique = len(set(numbers)) == 5
even_count = sum(number.is_integer() and int(number) % 2 == 0
                 for number in numbers)
negative_count = sum(number < 0 for number in numbers)
in_range_count = sum(-256 <= number <= 1024 for number in numbers)

print("Все числа уникальны:", all_unique)
print("Количество чётных:", even_count)
print("Количество отрицательных:", negative_count)
print("Количество в диапазоне [-256; 1024]:", in_range_count)