"""5. Проверка простого числа"""

def is_prime(n):
    if n < 2:
        return False

    divisor = 2
    while divisor * divisor <= n:
        if n % divisor == 0:
            return False
        divisor += 1

    return True

number = int(input("Введите целое число: "))
print(is_prime(number))

